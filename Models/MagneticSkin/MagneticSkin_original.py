def S_trajectory(points, height):
    """
    Generates an S-shaped trajectory
    """

    pts = np.array(points)
    x_vals = np.unique(pts[:, 0])

    trayectoria = []
    invertir = False

    for x in x_vals:
        columna = pts[pts[:, 0] == x]
        columna = columna[np.argsort(columna[:, 1])]
        if invertir:
            columna = columna[::-1]

        for p in columna:
            x_, y_ = p
            trayectoria.append([x_, y_, height])  

        invertir = not invertir

    return np.array(trayectoria)



