def calculate_B_field(distance_r_m, magnetic_moment_direction, mu_magnitude):
    """
    Calculates the magnetic field B generated by a magnetic dipole at a given point
    using the standard dipole field equation in SI units.

    Parameters
    ----------
    distance_r_m : array-like, shape (3,)
        Vector (in meters) from the magnetic dipole to the observation point.
    magnetic_moment_direction : array-like, shape (3,)
        Unit vector indicating the direction of the magnetic moment.
    mu_magnitude : float
        Magnitude of the magnetic moment in A·m².

    Returns
    -------
    B_field_uT : ndarray, shape (3,)
        Magnetic field vector at the observation point, in microTesla (µT).
    """

    r = np.array(distance_r_m)  

    r_magnitude = np.linalg.norm(r) 
    r_hat = r / r_magnitude
    Mu_hat = magnetic_moment_direction
    mu = [x * mu_magnitude for x in Mu_hat]

    # Compute the dipole field tensor: 3*r̂*r̂ᵀ - I
    tensor = 3 * np.outer(r_hat, r_hat) - np.identity(3)

    # Apply the formula: B = (μ₀ / 4π) * (tensor ⋅ μ) / |r|³
    numerator = np.matmul(tensor, mu)
    denominator = 4 * np.pi * (abs(r_magnitude)**3)

    # Magnetic field B in Tesla
    B_field = numerator / denominator

    # Convert Tesla to microTesla (1e6) or miliTesla (1e3)
    B_field_uT = B_field * 1e6   

    return B_field_uT
    
def taxel_grid(n):
    k = int(np.log2(np.sqrt(n)))
    p = 2**k

    while n % p != 0:
        p //= 2
    return n // p, p


def get_taxels(
    xmin, xmax,
    ymin, ymax,
    sphere_radius = 3*1e-3,
):
    Nx, Ny = taxel_grid(int(level_taxels))  

    xmin_safe = xmin + sphere_radius
    xmax_safe = xmax - sphere_radius
    ymin_safe = ymin + sphere_radius
    ymax_safe = ymax - sphere_radius
    Lx = xmax_safe - xmin_safe
    Ly = ymax_safe - ymin_safe


    dx = Lx / Nx
    dy = Ly / Ny


    #Taxels centers 
    center_taxels = []
    for iy in range(Ny):
        for ix in range(Nx):

            cx = xmin_safe + (ix + 0.5) * dx
            cy = ymin_safe + (iy + 0.5) * dy

            tid = iy * Nx + ix
            center_taxels.append((cx, cy))

    cx_skin = (xmin + xmax) / 2
    cy_skin = (ymin + ymax) / 2

    return center_taxels



